export function buildKoreanSurnamesJson() {
  const finalSurnames = SURNAMES_DATABASE.map(item => ({
    surname: item.surname,
    hanja: item.hanja,
    altHanja: item.altHanja || [item.hanja],
    meaning: item.meaning,
    ratioPercent: item.ratioPercent,
    rank: item.rank,
    isTwoSyllable: item.surname.length === 2
  }));

  const outputPath = path.join(dataDir, 'korean_surnames_all.json');
  fs.writeFileSync(outputPath, JSON.stringify(finalSurnames, null, 2), 'utf8');
  console.log(`Saved ${outputPath} (${finalSurnames.length} entries)`);
  return finalSurnames;
}

if (process.argv[1] && process.argv[1].endsWith('build_korean_surnames.mjs')) {
  buildKoreanSurnamesJson();
}
