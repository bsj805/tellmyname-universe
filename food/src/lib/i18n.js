export function normalizeLang(raw) {
  if (!raw || typeof raw !== 'string') return 'ko';
  const clean = raw.trim().toLowerCase().split(/[-_]/)[0];
  const found = SUPPORTED_LANGUAGES.find(l => l.code === clean);
  return found ? found.code : 'ko';
}

/**
 * Detect language based on priority:
 * 1. urlLang (?lang=...)
 * 2. cookieLang (mk_lang cookie)
 * 3. acceptLanguage (HTTP header) or navigatorLanguages (browser array)
 * 4. Fallback 'ko'
 *
 * @param {object} options
 * @param {string} [options.urlLang]
 * @param {string} [options.cookieLang]
 * @param {string} [options.acceptLanguage]
 * @param {string[]} [options.navigatorLanguages]
 * @returns {string}
 */
export function detectLanguage({ urlLang, cookieLang, acceptLanguage, navigatorLanguages } = {}) {
  // 1. URL Parameter
  if (urlLang && typeof urlLang === 'string' && urlLang.trim()) {
    const norm = normalizeLang(urlLang);
    const clean = urlLang.trim().toLowerCase().split(/[-_]/)[0];
    if (SUPPORTED_LANG_CODES.includes(clean)) {
      return norm;
    }
    // If explicit invalid/unsupported urlLang was provided, normalizeLang returns 'ko'
    return norm;
  }

  // 2. Cookie (mk_lang)
  if (cookieLang && typeof cookieLang === 'string' && cookieLang.trim()) {
    const clean = cookieLang.trim().toLowerCase().split(/[-_]/)[0];
    if (SUPPORTED_LANG_CODES.includes(clean)) {
      return clean;
    }
  }

  // 3. Accept-Language header (RFC 2616 quality-value parser)
  if (acceptLanguage && typeof acceptLanguage === 'string' && acceptLanguage.trim()) {
    const parts = acceptLanguage
      .split(',')
      .map(part => {
        const [langPart, qPart] = part.trim().split(';');
        let q = 1.0;
        if (qPart) {
          const qMatch = qPart.match(/q=\s*([0-9.]+)/i);
          if (qMatch) q = parseFloat(qMatch[1]) || 0;
        }
        return { lang: langPart.trim(), q };
      })
      .sort((a, b) => b.q - a.q);

    for (const item of parts) {
      const clean = item.lang.toLowerCase().split(/[-_]/)[0];
      if (SUPPORTED_LANG_CODES.includes(clean)) {
        return clean;
      }
    }
  }

  // 4. Browser Navigator Languages array
  if (Array.isArray(navigatorLanguages) && navigatorLanguages.length > 0) {
    for (const item of navigatorLanguages) {
      if (typeof item === 'string' && item.trim()) {
        const clean = item.trim().toLowerCase().split(/[-_]/)[0];
        if (SUPPORTED_LANG_CODES.includes(clean)) {
          return clean;
        }
      }
    }
  }

  // 5. Default fallback
  return 'ko';
}

/**
 * Translate a UI string key with variable placeholder substitution.
 * Fallback priority: UI_STRINGS[lang][key] -> UI_STRINGS['ko'][key] -> key
 *
 * @param {string} lang - Language code
 * @param {string} key - UI string key
 * @param {object} [vars={}] - Variables to substitute in {varName}
 * @returns {string}
 */
export function t(lang, key, vars = {}) {
  const norm = normalizeLang(lang);
  let str = UI_STRINGS[norm]?.[key];
  if (typeof str !== 'string' || !str) {
    str = UI_STRINGS['ko']?.[key];
  }
  if (typeof str !== 'string') {
    return String(key);
  }
  return str.replace(/\{(\w+)\}/g, (match, param) => {
    return (vars && vars[param] !== undefined) ? String(vars[param]) : match;
  });
}

/**
 * Localizes a food item.
 * - For Korean: preserves original name, tagline, originBadge.
 * - For non-Korean: looks up dict entry ({code: {name, tagline}}).
 *   If found, localized name and tagline are applied.
 *   If missing, name falls back to englishName (or food.name), tagline is empty, isLocalized=false.
 *   Korean is never leaked into non-Korean food copies.
 *
 * @param {object} food - Base food object
 * @param {string} [lang='ko'] - Target language code
 * @param {object} [dict=null] - Localized foods dictionary { code: { name, tagline } }
 * @returns {object} Localized copy of food
 */
export function localizeFood(food, lang = 'ko', dict = null) {
  if (!food) return food;

  const norm = normalizeLang(lang);
  if (norm === 'ko') {
    return {
      ...food,
      isLocalized: true
    };
  }

  // Resolve code key
  let codeKey = null;
  if (food.code) {
    codeKey = String(food.code).padStart(5, '0');
  } else if (food.index !== undefined && food.index !== null) {
    codeKey = String(food.index).padStart(5, '0');
  } else if (food.id && /^food_\d+$/.test(food.id)) {
    codeKey = String(food.id.replace('food_', '')).padStart(5, '0');
  }

  const entry = (dict && codeKey && dict[codeKey]) ? dict[codeKey] : null;

  let name;
  let tagline;
  let isLocalized;

  if (entry && entry.name && typeof entry.name === 'string' && entry.name.trim()) {
    name = entry.name.trim();
    tagline = (entry.tagline && typeof entry.tagline === 'string') ? entry.tagline.trim() : '';
    isLocalized = true;
  } else {
    name = food.englishName || food.name || '';
    // Tagline fallback: omit Korean tagline for non-ko fallback
    const rawTagline = food.tagline || '';
    const hasHangul = /[\uAC00-\uD7A3\u1100-\u11FF\u3130-\u318F]/.test(rawTagline);
    tagline = hasHangul ? '' : rawTagline;
    isLocalized = false;
  }

  // Localize origin badge if originGroup exists
  let originBadge = food.originBadge;
  if (food.originGroup) {
    const badgeKey = 'origin_' + food.originGroup;
    const localizedBadge = t(norm, badgeKey);
    if (localizedBadge && localizedBadge !== badgeKey) {
      originBadge = localizedBadge;
    }
  }

  return {
    ...food,
    name,
    tagline,
    originBadge,
    isLocalized
  };
}
