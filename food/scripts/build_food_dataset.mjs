// scripts/build_food_dataset.mjs
// Builds:
// 1. data/foods_master.json
// 2. data/category_stats_report.json
// 3. src/lib/food_dataset.js (Self-contained ESM module with embedded data, 0 Node fs dependency, browser & Cloudflare Worker ready)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  MEAL_CATEGORIES,
  FOOD_ORIGIN_GROUPS,
  CATEGORY_MAX_LIMITS
} from '../src/lib/constants.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT_DIR, 'data');
const RAW_FILE = path.join(DATA_DIR, 'raw_foods_collected.json');
const MASTER_JSON = path.join(DATA_DIR, 'foods_master.json');
const STATS_JSON = path.join(DATA_DIR, 'category_stats_report.json');
const LIB_FILE = path.join(ROOT_DIR, 'src', 'lib', 'food_dataset.js');

// Parse CLI flags (e.g. --cap=30)
let cliCap = null;
for (const arg of process.argv.slice(2)) {
  if (arg.startsWith('--cap=')) {
    const val = parseInt(arg.split('=')[1], 10);
    if (!isNaN(val) && val > 0) cliCap = val;
  }
}

export function buildFoodDataset(capOverride = cliCap) {
  console.log('=== [Mukbang] Food Dataset & Taxonomy Builder ===');
  if (!fs.existsSync(RAW_FILE)) {
    throw new Error(`Raw foods file not found: ${RAW_FILE}. Run collect_all_foods.mjs first.`);
  }

  const rawFoods = JSON.parse(fs.readFileSync(RAW_FILE, 'utf8'));
  console.log(`Loaded ${rawFoods.length} raw foods.`);

  const foodsById = {};
  const foodsByCode = {};
  for (const f of rawFoods) {
    foodsById[f.id] = f;
    foodsByCode[f.code] = f;
  }

  // Group foods into candidate meal pools
  const rawPools = {
    breakfast: [],
    lunch: [],
    snack: [],
    dinner: [],
    night: []
  };

  for (const food of rawFoods) {
    const meals = food.candidateMeals || [food.primaryMeal || 'lunch'];
    for (const m of meals) {
      if (rawPools[m]) {
        rawPools[m].push(food);
      }
    }
  }

  // Stratified round-robin capping helper
  // Ensures all origin groups (School lunch, Michelin, Raw natural, Cinema/Unique, Popular) are evenly represented when a cap is applied.
  function applyCapStratified(pool, cap) {
    if (!cap || cap >= pool.length) return [...pool];

    // Bucket by originGroup
    const buckets = {};
    for (const f of pool) {
      if (!buckets[f.originGroup]) buckets[f.originGroup] = [];
      buckets[f.originGroup].push(f);
    }

    const groupKeys = Object.keys(buckets).sort();
    const result = [];
    let added = true;
    let round = 0;

    while (result.length < cap && added) {
      added = false;
      for (const k of groupKeys) {
        if (result.length >= cap) break;
        if (round < buckets[k].length) {
          result.push(buckets[k][round]);
          added = true;
        }
      }
      round++;
    }
    return result;
  }

  const activePools = {};
  const stats = {
    totalRawFoods: rawFoods.length,
    buildTime: new Date().toISOString(),
    capSetting: capOverride || 'UNLIMITED',
    categories: {}
  };

  for (const cat of MEAL_CATEGORIES) {
    const pool = rawPools[cat.key] || [];
    const targetCap = capOverride || CATEGORY_MAX_LIMITS[cat.key] || null;
    const capped = applyCapStratified(pool, targetCap);
    activePools[cat.key] = capped;

    const originBreakdown = {};
    for (const f of capped) {
      originBreakdown[f.originGroup] = (originBreakdown[f.originGroup] || 0) + 1;
    }

    stats.categories[cat.key] = {
      label: cat.label,
      fullLabel: cat.fullLabel,
      emoji: cat.emoji,
      timeRange: cat.timeRangeText,
      rawCandidatesCount: pool.length,
      activeCount: capped.length,
      originBreakdown
    };
  }

  // 1. Save data/foods_master.json
  const masterPayload = {
    version: '1.0.0',
    totalFoods: rawFoods.length,
    foods: rawFoods,
    poolsByMeal: activePools,
    stats
  };
  fs.writeFileSync(MASTER_JSON, JSON.stringify(masterPayload, null, 2), 'utf8');
  console.log(`✔ Saved master dataset to ${MASTER_JSON}`);

  // 2. Save data/category_stats_report.json
  fs.writeFileSync(STATS_JSON, JSON.stringify(stats, null, 2), 'utf8');
  console.log(`✔ Saved category stats report to ${STATS_JSON}`);

  // 3. Generate self-contained src/lib/food_dataset.js
  const libCode = `// src/lib/food_dataset.js — Self-contained food master dataset
// Auto-generated by scripts/build_food_dataset.mjs. Do not edit manually.
// Zero Node fs dependencies: directly imported by browser (web/js/app.js) and Cloudflare Workers (worker.js).

export const ALL_FOODS = ${JSON.stringify(rawFoods, null, 2)};

export const FOODS_BY_ID = ${JSON.stringify(foodsById, null, 2)};

export const FOODS_BY_CODE = ${JSON.stringify(foodsByCode, null, 2)};

export const POOLS_BY_MEAL = ${JSON.stringify(activePools, null, 2)};

export const CATEGORY_STATS = ${JSON.stringify(stats, null, 2)};

// Alias for backwards compatibility with web/js/app.js
export const FOODS_BY_MEAL = POOLS_BY_MEAL;
export const MEAL_POOLS = POOLS_BY_MEAL;
export const poolsByMeal = POOLS_BY_MEAL;

export function getFoodByCodeOrId(key) {
  if (!key) return null;
  const str = String(key).trim();
  if (FOODS_BY_ID[str]) return FOODS_BY_ID[str];
  if (FOODS_BY_CODE[str]) return FOODS_BY_CODE[str];
  const padded = str.padStart(5, '0');
  if (FOODS_BY_CODE[padded]) return FOODS_BY_CODE[padded];
  return null;
}

export function getPoolsWithCap(cap) {
  if (!cap || typeof cap !== 'number' || cap <= 0) return POOLS_BY_MEAL;
  const result = {};
  for (const [meal, list] of Object.entries(POOLS_BY_MEAL)) {
    result[meal] = list.slice(0, cap);
  }
  return result;
}

export default {
  ALL_FOODS,
  FOODS_BY_ID,
  FOODS_BY_CODE,
  POOLS_BY_MEAL,
  FOODS_BY_MEAL: POOLS_BY_MEAL,
  MEAL_POOLS: POOLS_BY_MEAL,
  CATEGORY_STATS,
  getFoodByCodeOrId,
  getPoolsWithCap
};
`;

  fs.writeFileSync(LIB_FILE, libCode, 'utf8');
  console.log(`✔ Generated self-contained library ${LIB_FILE}`);

  console.log('\n[Active Meal Pools Summary]');
  for (const cat of MEAL_CATEGORIES) {
    console.log(`  - ${cat.emoji} ${cat.fullLabel.padEnd(16)}: ${activePools[cat.key].length}개 메뉴`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  buildFoodDataset();
}
