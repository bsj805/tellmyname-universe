export function getUiStrings(lang = 'ko') {
  return UI_STRINGS[normalizeLang(lang)] || UI_STRINGS.ko;
}

/**
 * Nested path translation retriever with English and Korean fallbacks
 * @param {string} lang
 * @param {string} pathStr
 * @param {Record<string, string|number>} [params={}]
 * @returns {any}
 */
export function getTranslation(lang, pathStr, params = {}) {
  const selectedLang = normalizeLang(lang);
  const parts = String(pathStr).split('.');
  let current = UI_STRINGS[selectedLang];

  for (const part of parts) {
    if (current && current[part] !== undefined) {
      current = current[part];
    } else {
      let fb = UI_STRINGS.en;
      for (const p of parts) fb = fb?.[p];
      if (fb !== undefined) {
        current = fb;
        break;
      }
      let fbKo = UI_STRINGS.ko;
      for (const p of parts) fbKo = fbKo?.[p];
      current = fbKo;
      break;
    }
  }

  if (typeof current === 'string') {
    let result = current;
    for (const [k, v] of Object.entries(params)) {
      result = result.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return result;
  }
  return current;
}

/**
 * Flat/nested translation helper compatible with {var} interpolation.
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, string|number>} [vars={}]
 * @returns {string}
 */
export function t(lang, key, vars = {}) {
  const res = getTranslation(lang, key, vars);
  return typeof res === 'string' ? res : String(key);
}

