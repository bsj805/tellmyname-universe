/**
 * Localizes a vehicle/mount concept object for any of the 14 supported languages.
 * Guarantees 0 Korean leakage when lang !== 'ko', and populates dual fields
 * (`estimatedPrice` & `estimatedSalary`, `specialFeature` & `specialDuty`).
 *
 * @param {object} car Base vehicle concept
 * @param {string} [lang='ko'] Target language code
 * @param {string|null} [nameQuery=null] Current driver/owner name
 * @returns {object}
 */
export function localizeCarConcept(car, lang = 'ko', nameQuery = null) {
  if (!car) return car;

  const selectedLang = normalizeLang(lang);

  // For Korean: preserve original Korean strings and populate all dual property aliases
  if (selectedLang === 'ko') {
    const era = car.era || car.builtYear || '';
    const estimatedPrice = car.estimatedPrice || car.estimatedSalary || car.estimatedValue || '';
    const specialFeature = car.specialFeature || car.specialDuty || '';
    return {
      ...car,
      era,
      builtYear: era,
      estimatedPrice,
      estimatedSalary: estimatedPrice,
      estimatedValue: estimatedPrice,
      specialFeature,
      specialDuty: specialFeature
    };
  }

  const dict = UI_STRINGS[selectedLang] || UI_STRINGS.en;
  const enDict = UI_STRINGS.en;
  const lv = Number(car.level) || 0;

  const zoneLabel = dict.zones?.[car.zone] || enDict.zones?.[car.zone] || car.zone;
  const realityLabel = dict.reality?.[car.realityType] || enDict.reality?.[car.realityType] || car.realityType;
  const categoryLabel = dict.categories?.[car.category] || enDict.categories?.[car.category] || 'Special Ride';
  const tierName = dict.tiers?.[car.tier] || enDict.tiers?.[car.tier] || `Tier ${car.tier}`;

  const masterCar = MASTER_CARS?.[lv];
  const masterEn = car.en || masterCar?.en;
  const hasHangul = (s) => /[가-힣]/.test(String(s || ''));

  const title = masterEn?.title || (hasHangul(car.title) ? `Level ${lv} Multiverse Ride` : car.title);
  const rawEra = car.era || car.builtYear;
  const era = masterEn?.era || masterEn?.builtYear || (hasHangul(rawEra) ? 'Contemporary & Multiverse Era' : rawEra);
  const rawPrice = car.estimatedPrice || car.estimatedSalary || car.estimatedValue;
  const estimatedPrice = masterEn?.estimatedPrice || masterEn?.estimatedSalary || masterEn?.estimatedValue || (hasHangul(rawPrice) ? 'Priceless' : rawPrice);
  const rawFeature = car.specialFeature || car.specialDuty;
  const specialFeature = masterEn?.specialFeature || masterEn?.specialDuty || (hasHangul(rawFeature) ? 'Delivers extraordinary multiverse mobility performance.' : rawFeature);
  const aiVerdict = masterEn?.aiVerdict || (hasHangul(car.aiVerdict) ? 'An iconic ride certified by the Multiverse Garage Registry.' : car.aiVerdict);

  return {
    ...car,
    title,
    zoneLabel,
    realityLabel,
    categoryLabel,
    tierName,
    era,
    builtYear: era,
    estimatedPrice,
    estimatedSalary: estimatedPrice,
    estimatedValue: estimatedPrice,
    specialFeature,
    specialDuty: specialFeature,
    aiVerdict
  };
}

