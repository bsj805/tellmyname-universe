export const MASTER_TIERS_500 = MASTER_TIERS_1001;

console.log('=== [MyJob] Building Taxonomy Dataset & Master JS Module ===');

if (!fs.existsSync(FULL_JSON)) {
  console.error(`Error: ${FULL_JSON} not found. Run scripts/build_full_dataset.py first.`);
  process.exit(1);
}

const rawJobs = JSON.parse(fs.readFileSync(FULL_JSON, 'utf8'));
console.log(`Loaded ${rawJobs.length} raw jobs from ${FULL_JSON}`);

if (rawJobs.length !== 1001) {
  throw new Error(`Expected exactly 1001 jobs, got ${rawJobs.length}`);
}

// 1. Build src/lib/master_dataset.js
const masterDatasetJsPath = path.join(SRC_LIB_DIR, 'master_dataset.js');
console.log(`Generating ${masterDatasetJsPath}...`);

const masterDatasetContent = `// src/lib/master_dataset.js — 0~1000 Level Master Occupation Dataset (1,001 items)
// Generated by scripts/build_taxonomy_dataset.mjs — DO NOT EDIT MANUALLY

export const MASTER_TIERS_1001 = ${JSON.stringify(MASTER_TIERS_1001, null, 2)};

export const MASTER_TIERS_500 = MASTER_TIERS_1001;

export const MASTER_JOBS = ${JSON.stringify(rawJobs, null, 2)};

export const MASTER_HOUSES = MASTER_JOBS;

const _jobsByLevelMap = new Map();
for (let i = 0; i < MASTER_JOBS.length; i++) {
  _jobsByLevelMap.set(MASTER_JOBS[i].level, MASTER_JOBS[i]);
}

/**
 * 단계(0..1000)를 받아 직업 컨셉 객체를 반환합니다.
 */
export function lookupJobByLevel(level) {
  const lv = Math.max(0, Math.min(1000, Math.floor(Number(level) || 0)));
  return _jobsByLevelMap.get(lv) || MASTER_JOBS[0];
}

export const lookupHouseByLevel = lookupJobByLevel;
`;

fs.writeFileSync(masterDatasetJsPath, masterDatasetContent, 'utf8');
console.log(`✔ Generated src/lib/master_dataset.js (${(Buffer.byteLength(masterDatasetContent) / 1024 / 1024).toFixed(2)} MB)`);

// 2. Generate 20 chunk files in data/chunks/
console.log('Generating 20 chunk files in data/chunks/...');

for (let i = 0; i < MASTER_TIERS_1001.length; i++) {
  const tierCfg = MASTER_TIERS_1001[i];
  const [startLv, endLv] = tierCfg.range;
  const chunkItems = rawJobs.filter(j => j.level >= startLv && j.level <= endLv);
  const chunkIndexPadded = String(i).padStart(2, '0');

  const jobChunkFile = path.join(CHUNKS_DIR, `jobs-chunk-${chunkIndexPadded}.json`);
  const houseChunkFile = path.join(CHUNKS_DIR, `houses-chunk-${chunkIndexPadded}.json`);

  const chunkJson = JSON.stringify(chunkItems, null, 2);
  fs.writeFileSync(jobChunkFile, chunkJson, 'utf8');
  fs.writeFileSync(houseChunkFile, chunkJson, 'utf8');

  console.log(`  - Chunk ${chunkIndexPadded} (Lv.${startLv}..${endLv}, ${chunkItems.length} items): jobs-chunk-${chunkIndexPadded}.json & houses-chunk-${chunkIndexPadded}.json`);
}

// 3. Build data/concept_table_summary.json
const summaryPath = path.join(DATA_DIR, 'concept_table_summary.json');
const categoryStats = {};
for (const job of rawJobs) {
  categoryStats[job.category] = (categoryStats[job.category] || 0) + 1;
}

const summaryData = {
  totalLevels: rawJobs.length,
  minLevel: rawJobs[0].level,
  maxLevel: rawJobs[rawJobs.length - 1].level,
  realCount: rawJobs.filter(j => j.realityType === 'REAL').length,
  fictionCount: rawJobs.filter(j => j.realityType === 'FICTION').length,
  badZoneCount: rawJobs.filter(j => j.zone === 'BAD').length,
  goodZoneCount: rawJobs.filter(j => j.zone === 'GOOD').length,
  tiersCount: MASTER_TIERS_1001.length,
  tiers: MASTER_TIERS_1001.map(t => ({
    tier: t.tier,
    name: t.name,
    range: t.range,
    zone: t.zone,
    zoneLabel: t.zoneLabel,
    itemCount: t.range[1] - t.range[0] + 1
  })),
  categoryBreakdown: categoryStats,
  landmarkSamples: {
    level0: rawJobs[0].title,
    level100: rawJobs[100].title,
    level250: rawJobs[250].title,
    level600: rawJobs[600].title,
    level999: rawJobs[999].title,
    level1000: rawJobs[1000].title
  },
  generatedAt: new Date().toISOString()
};

fs.writeFileSync(summaryPath, JSON.stringify(summaryData, null, 2), 'utf8');
console.log(`✔ Generated data/concept_table_summary.json`);
console.log('=== All Dataset & Taxonomy Files Successfully Built! ===');
